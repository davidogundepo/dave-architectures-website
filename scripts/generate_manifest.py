"""
Regenerate lib/videos.generated.ts.

Reads what actually exists on disk and in the upload record, so the site only
ever renders clips whose assets are really there:

    public/posters/<slug>.jpg   from scripts/build_media.py
    public/preview/<slug>.mp4   from scripts/build_media.py
    lib/captions.json           from scripts/build_media.py
    lib/uploads.json            from scripts/upload_media.py

Run it after build_media.py and after upload_media.py.
"""

import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "lib", "videos.generated.ts")
POSTER_DIR = os.path.join(ROOT, "public", "posters")
PREVIEW_DIR = os.path.join(ROOT, "public", "preview")
CAPTIONS = os.path.join(ROOT, "lib", "captions.json")
UPLOADS = os.path.join(ROOT, "lib", "uploads.json")

# Slugified portal prefix -> brand id in lib/brands.ts
BRAND_BY_PREFIX = {
    "bayut-com-ae": "bayut",
    "christiesrealestate-com": "christies",
    "coldwellbankerluxury-com": "coldwell-banker",
    "domain-com-au": "domain",
    "mansionglobal-com": "mansion-global",
    "nigeriapropertycentre-com": "npc",
    "pamgolding-co-za": "pam-golding",
    "propertyfinder-ae": "property-finder",
    "realestate-com-au": "realestate-au",
    "rightmove-co-uk": "rightmove",
    "savills-co-uk": "savills",
    "sothebysrealty-com-eng": "sothebys",
    "zillow-com-us": "zillow",
}

SLUG_RE = re.compile(r"^(?P<portal>.+)-(?P<index>\d+)$")


def load(path, default):
    if os.path.exists(path):
        try:
            with open(path) as f:
                return json.load(f)
        except Exception:
            pass
    return default


def ts(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def main():
    captions = load(CAPTIONS, {})
    uploads = load(UPLOADS, {})

    posters = {
        f[:-4] for f in os.listdir(POSTER_DIR) if f.endswith(".jpg")
    } if os.path.isdir(POSTER_DIR) else set()

    previews = {
        f[:-4] for f in os.listdir(PREVIEW_DIR) if f.endswith(".mp4")
    } if os.path.isdir(PREVIEW_DIR) else set()

    clips, unknown, no_video = [], set(), []

    for slug in sorted(posters):
        m = SLUG_RE.match(slug)
        if not m:
            continue

        brand = BRAND_BY_PREFIX.get(m.group("portal"))
        if not brand:
            unknown.add(m.group("portal"))
            continue

        src = uploads.get(slug, {}).get("url")
        if not src:
            no_video.append(slug)

        index = int(m.group("index"))
        caption = captions.get(slug, {})

        clips.append({
            "id": slug,
            "brandId": brand,
            "index": index,
            "orientation": "landscape" if index <= 2 else "portrait",
            "src": src,
            "preview": f"/preview/{slug}.mp4" if slug in previews else None,
            "poster": f"/posters/{slug}.jpg",
            "title": caption.get("title"),
            "location": caption.get("location"),
            "note": caption.get("note"),
        })

    if unknown:
        print(f"  WARN  unmapped portals (add to BRAND_BY_PREFIX): {sorted(unknown)}")
    if no_video:
        print(f"  NOTE  {len(no_video)} clips have no uploaded video yet "
              f"(poster + preview only): {no_video[0]} …")

    clips.sort(key=lambda c: (c["brandId"], c["index"]))

    lines = [
        "// AUTO-GENERATED by scripts/generate_manifest.py — do not edit by hand.",
        "",
        "import type { Clip } from './types';",
        "",
        "export const clips: Clip[] = [",
    ]
    for c in clips:
        fields = [
            f"    id: {ts(c['id'])},",
            f"    brandId: {ts(c['brandId'])},",
            f"    index: {c['index']},",
            f"    orientation: {ts(c['orientation'])},",
            f"    src: {ts(c['src'] or '')},",
        ]
        for key in ("preview", "poster", "title", "location", "note"):
            if c[key]:
                fields.append(f"    {key}: {ts(c[key])},")
        lines.append("  {\n" + "\n".join(fields) + "\n  },")
    lines.append("];")
    lines.append("")

    with open(OUT, "w") as f:
        f.write("\n".join(lines))

    by_brand: dict[str, int] = {}
    for c in clips:
        by_brand[c["brandId"]] = by_brand.get(c["brandId"], 0) + 1
    print(f"wrote {OUT} — {len(clips)} clips across {len(by_brand)} brands")


if __name__ == "__main__":
    main()
